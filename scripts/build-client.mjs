/**
 * Deterministic client-bundle builder (no third-party dependencies).
 *
 *   node scripts/build-client.mjs           build lib/client.js
 *   node scripts/build-client.mjs --check   fail if lib/client.js is stale
 *
 * Pipeline (方案 §1.5 / Step 3):
 *   - "// @include <path>"        → plain client fragment (verbatim, indented)
 *   - "// @inline-shared <path>"  → src/shared module with `export ` stripped
 *   - "// @builtin-packs"         → const BUILTIN_PACKS = {...} (validated themes/ snapshot)
 *   - __PLUGIN_ID__ / __VERSION__ / __MARKER__ substitution
 *   - vm.Script syntax check, then write lib/client.js
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync, statSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import vm from "node:vm";
import { validateThemePack, validateThemeCss } from "../src/shared/pack-schema.js";

const root = fileURLToPath(new URL("..", import.meta.url));
const pkg = JSON.parse(readFileSync(path.join(root, "package.json"), "utf8"));
const ENTRY = path.join(root, "src", "client", "main.js");
const OUT = path.join(root, "lib", "client.js");
const THEMES = path.join(root, "themes");
const MARKER = process.env.DSHTE_BUILD_MARKER || "skeleton-v1";
const BANNER = "// Generated by scripts/build-client.mjs — do not edit directly.\n";
const INCLUDE = /^([ \t]*)\/\/ @include[ \t]+(\S+)[ \t]*$/gm;
const INLINE_SHARED = /^([ \t]*)\/\/ @inline-shared[ \t]+(\S+)[ \t]*$/gm;
const INLINE_CSS = /^([ \t]*)\/\/ @inline-css[ \t]+(\S+)[ \t]*$/gm;
const BUILTIN_MARKER = /^([ \t]*)\/\/ @builtin-packs[ \t]*$/gm;

function readNormalized(file) {
	return readFileSync(file, "utf8").replace(/\r\n?/g, "\n").replace(/\s+$/, "");
}

function indentBlock(text, indent) {
	return text.split("\n").map((line) => (line ? indent + line : "")).join("\n");
}

function expand(text, depth) {
	if (depth > 8) throw new Error("build-client: include depth exceeded (cycle?)");
	const withShared = text.replace(INLINE_SHARED, (_match, indent, relative) => {
		const file = path.resolve(path.dirname(ENTRY), relative);
		const source = readNormalized(file).replace(/^export\s+/gm, "");
		if (/^\s*(import|export)\s/m.test(source)) throw new Error(`build-client: shared file ${relative} has imports/exports that cannot be inlined`);
		return indentBlock(expand(source, depth + 1), indent);
	});
	const withCss = withShared.replace(INLINE_CSS, (_match, indent, relative) => {
		const file = path.resolve(path.dirname(ENTRY), relative);
		return indentBlock(`const ENGINE_CSS = ${JSON.stringify(readNormalized(file))};`, indent);
	});
	return withCss.replace(INCLUDE, (_match, indent, relative) => {
		const file = path.resolve(path.dirname(ENTRY), relative);
		return indentBlock(expand(readNormalized(file), depth + 1), indent);
	});
}

/** Snapshot + validate every built-in theme pack (read-only, embedded in the bundle). */
function loadBuiltinPacks() {
	const packs = {};
	if (!existsSync(THEMES)) return packs;
	for (const id of readdirSync(THEMES).sort()) {
		const directory = path.join(THEMES, id);
		if (!statSync(directory).isDirectory()) continue;
		const manifest = JSON.parse(readFileSync(path.join(directory, "theme.json"), "utf8"));
		const packResult = validateThemePack(manifest);
		if (!packResult.ok) {
			throw new Error(`build-client: builtin pack ${id} is invalid: ${packResult.errors.map((item) => `${item.path} ${item.message}`).join("; ")}`);
		}
		let css = null;
		if (typeof manifest.css === "string") {
			css = readFileSync(path.join(directory, manifest.css), "utf8");
			const cssResult = validateThemeCss(css, { filename: manifest.css });
			if (!cssResult.ok) {
				throw new Error(`build-client: builtin pack ${id} CSS is invalid: ${cssResult.errors.map((item) => `${item.path} ${item.message}`).join("; ")}`);
			}
		}
		packs[id] = { pack: manifest, css };
	}
	return packs;
}

function build() {
	const template = readNormalized(ENTRY);
	let output = expand(template, 0);
	const builtin = loadBuiltinPacks();
	output = output.replace(BUILTIN_MARKER, (_match, indent) => `${indent}const BUILTIN_PACKS = ${JSON.stringify(builtin)};`);
	output = output
		.replaceAll("__PLUGIN_ID__", pkg.name)
		.replaceAll("__VERSION__", pkg.version)
		.replaceAll("__MARKER__", MARKER)
		.replace(/\n+$/, "\n");
	if (/^[ \t]*\/\/ @(include|inline-shared|inline-css)[ \t]+\S+[ \t]*$/m.test(output) || /^[ \t]*\/\/ @builtin-packs[ \t]*$/m.test(output)) throw new Error("build-client: unexpanded build marker remains");
	new vm.Script(output, { filename: OUT }); // syntax check only; never executed here
	return BANNER + output;
}

const next = build();
if (process.argv.includes("--check")) {
	if (!existsSync(OUT)) {
		console.error("build-client: lib/client.js is missing; run: node scripts/build-client.mjs");
		process.exit(1);
	}
	const current = readFileSync(OUT, "utf8");
	if (current !== next) {
		console.error("build-client: lib/client.js is stale; run: node scripts/build-client.mjs");
		process.exit(1);
	}
	console.log(`build-client: lib/client.js is up to date (${Buffer.byteLength(next)} bytes, marker=${MARKER})`);
} else {
	mkdirSync(path.dirname(OUT), { recursive: true });
	writeFileSync(OUT, next);
	console.log(`build-client: wrote lib/client.js (${Buffer.byteLength(next)} bytes, marker=${MARKER})`);
}
